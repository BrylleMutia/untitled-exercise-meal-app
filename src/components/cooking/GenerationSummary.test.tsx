import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it, vi } from "vitest";
import type { ReactNode } from "react";
import type { GroupGeneration, GroupWeek } from "@/types/cookingGroup";
import { GenerationSummary } from "./GenerationSummary";

vi.mock("@/contexts/AppContext", () => ({ useApp: () => ({ snapshot: { userId: "self" } }) }));
vi.mock("@/components/ui/Modal", () => ({ Modal: ({ title, titlePlacement, children, footer }: { title: string; titlePlacement: string; children: ReactNode; footer: ReactNode }) => <div data-title-placement={titlePlacement}><h2>{title}</h2>{children}{footer}</div> }));

const generation: GroupGeneration = {
  id: "generation", weekOf: "2026-11-01", generatedBy: "Alex", createdAt: "2026-11-05T10:00:00Z", memberIds: ["self", "other"], acknowledged: false, superseded: false,
  assignmentCounts: [{ memberId: "self", count: 2 }, { memberId: "other", count: 0 }],
  batches: [{ recipeId: "recipe", name: "Saved recipe", yield: 4, portions: 2, batches: 1, leftovers: 2 }],
  personalReview: { policyVersion: "advisory_v1", recipeWarnings: [{ code: "avoided-food", recipeId: "recipe", recipeRevision: 1, recipeName: "Saved recipe", message: "Private ingredient conflict" }], dailyWarnings: [{ code: "daily-carbohydrate", date: "2026-11-05", recipeIds: ["recipe"], totalCarbs: null, limit: 50, message: "Private daily warning" }] },
};
const week: GroupWeek = { weekOf: generation.weekOf, revision: 1, recipes: [], assignments: [], grocery: null, generation, notices: [], group: { id: "group", revision: 1, weekStartsOn: 0, proposal: null, members: ["self", "other"].map(id => ({ id, name: "Alex", joinedAt: generation.createdAt })) } };
function render(value = generation) { return renderToStaticMarkup(<GenerationSummary generation={value} week={week} onClose={vi.fn()} />); }

describe("generation completion summary", () => {
  it("places its title in the content above the checkmark and generator details", () => {
    const html = render();
    expect(html).toContain('data-title-placement="content"');
    expect(html.indexOf("You&#x27;re all set!")).toBeLessThan(html.indexOf("data-generation-success-animation"));
    expect(html.indexOf("data-generation-success-animation")).toBeLessThan(html.indexOf("Generated by Alex"));
    expect(html).toContain("/animations/check-done.png");
    expect(html).toContain(">Done</button>");
  });
  it("omits the recorded warning review while keeping people, counts and cooking overview", () => {
    const html = render();
    expect(html).not.toContain("Your review at generation");
    expect(html).not.toContain("Private ingredient conflict");
    expect(html).not.toContain("Private daily warning");
    expect(html).not.toContain("Recipe warnings");
    expect(html).not.toContain("Daily preference warnings");
    expect(html).toContain("Selected people: Alex (you), Alex");
    expect(html).toContain("Alex: 0 new meal assignments");
    expect(html).toContain("Overview");
    expect(html).toContain("Saved recipe");
    expect(html).toContain("2 leftover servings");
  });
  it("preserves the superseded notice and handles absent private reviews", () => {
    const html = render({ ...generation, superseded: true, personalReview: undefined });
    expect(html).toContain("A newer generation supersedes this summary.");
    expect(html).not.toContain("No preference warnings were recorded");
  });
});
